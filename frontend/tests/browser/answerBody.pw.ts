import { expect, test } from '@playwright/test'

test('探索入口后的短补充保留正文、表格、代码及引用，刷新后完整恢复', async ({ page, request }) => {
  const conversation = await (await request.post('/api/projects/1/conversations')).json()
  await page.addInitScript(cid => {
    localStorage.setItem('ci.projectId', '1')
    localStorage.setItem('ci.activeConversation.1', cid)
  }, conversation.id)
  await page.goto('/')
  const input = page.locator('.wb-center textarea')
  await expect(input).toBeEnabled()
  await input.fill('已有策略与成绩 __fixture_preserve_body__')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByRole('button', { name: '停止生成', exact: true })).toHaveCount(0)
  const answer = page.locator('.assistant-answer')
  await expect(answer.getByRole('heading', { name: '已有策略' })).toBeVisible()
  await expect(answer).toContainText('补充：还可以对比另一种实现。')
  await expect(answer.locator('table')).toBeVisible()
  await expect(answer.locator('pre').first()).toContainText('value = 1')
  await expect(answer.getByRole('navigation', { name: '接着探索' })).toBeVisible()
  const saved = await (await request.get(`/api/projects/1/conversations/${conversation.id}/turns`)).json()
  const turn = saved.items.at(-1)
  expect(turn.answer.raw_text).toContain('## 已有策略')
  expect(turn.answer.raw_text).toContain('补充：')
  expect(turn.answer.raw_text).toContain('我先查资料')
  expect(turn.answer.citations[0].path).toBe('store.py')
  await page.reload()
  await expect(answer.getByRole('heading', { name: '已有策略' })).toBeVisible()
  await expect(answer).toContainText('补充：还可以对比另一种实现。')
  await expect(answer.locator('table')).toBeVisible()
  await expect(answer.getByRole('navigation', { name: '接着探索' })).toBeVisible()
})
