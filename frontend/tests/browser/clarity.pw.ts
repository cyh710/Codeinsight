import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'

test.beforeEach(async ({ page, request }) => {
  const conversation = await (await request.post('/api/projects/1/conversations')).json()
  await page.addInitScript(cid => localStorage.setItem('ci.activeConversation.1', cid), conversation.id)
  await page.goto('/')
  await expect(page.locator('.wb-center textarea')).toBeEnabled()
  await expect(page.getByRole('navigation', { name: '项目探索入口' })).toBeVisible()
})

test('精简的关联条仍能固定、取消和重新跟随，路径在项目菜单可读', async ({ page }) => {
  await expect(page.locator('footer.wb-status')).toHaveCount(0)
  await expect(page.locator('.project-guide')).not.toContainText('不额外调用模型')
  await expect(page.locator('.reading-context')).toHaveCount(0)
  await expect(page.locator('.sidebar-project-header')).not.toContainText('工作区')
  await page.getByRole('button', { name: '项目操作', exact: true }).click()
  await expect(page.locator('.sidebar-menu-path')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('navigation', { name: '左栏内容' }).getByRole('button', { name: '文件', exact: true }).click()
  const choose = (path: string) => page.getByTestId('tree-file').filter({ hasText: path }).click()
  const target = page.locator('.reading-target summary')
  const pin = page.getByRole('button', { name: '固定提问目标', exact: true })
  await choose('store.py')
  await expect(target).toContainText('store.py')
  await pin.click()
  await expect(pin).toHaveAttribute('aria-pressed', 'true')
  await choose('large.py')
  await expect(page.locator('#workspace-materials')).toContainText('451 行')
  await expect(target).toContainText('store.py')
  await pin.click()
  await expect(target).toContainText('large.py')
  await expect(pin).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: '取消关联', exact: true }).click()
  await choose('store.py')
  await expect(target).toHaveCount(0)
  await page.getByRole('button', { name: '跟随阅读', exact: true }).click()
  await expect(target).toContainText('store.py')
  await target.click()
  await expect(page.locator('.reading-target-preview')).toContainText('store.py')
})

test('辅助信息统一展开，局部教材和新来源提示在窄屏仍可操作', async ({ page }) => {
  await page.getByRole('navigation', { name: '项目探索入口' }).getByRole('button').first().click()
  const next = page.getByRole('navigation', { name: '接着探索' }).last()
  await expect(next).toBeVisible({ timeout: 15000 })
  const answer = page.locator('.assistant-answer').last()
  await expect(answer.getByText('来源与查阅过程', { exact: true })).toBeVisible()
  await expect(answer.getByText('代码事实 · 2 条', { exact: true })).toBeHidden()
  await answer.locator('.reply-citation').first().click()
  await expect(page.locator('#workspace-materials').getByRole('spinbutton', { name: '跳到行号', exact: true })).toBeVisible()
  await expect(page.locator('#workspace-materials .monaco-editor')).toBeVisible()
  await page.screenshot({ path: resolve('..', '.ci/browser/clarity-answer.png'), animations: 'disabled' })
  await answer.getByText('来源与查阅过程', { exact: true }).click()
  await expect(answer.getByRole('button', { name: '查看来源', exact: true })).toBeVisible()
  await expect(answer.getByText('代码事实 · 2 条', { exact: true })).toHaveCount(0)
  await answer.getByText('来源与查阅过程', { exact: true }).click()
  await next.getByRole('button', { name: /理解事务的提交与回滚/ }).click()
  const context = page.locator('.context-reading')
  await expect(context.locator('.context-excerpt')).toContainText('写入先开启事务')
  await expect(context).not.toContainText('本回合已解释的要点')
  await expect(context).not.toContainText('围绕这次问题理解')
  const full = context.getByRole('button', { name: '阅读全文', exact: true })
  await expect(full).toBeVisible()
  const primary = await full.evaluate(el => ({ size: parseFloat(getComputedStyle(el).fontSize), height: el.getBoundingClientRect().height }))
  expect(primary.size).toBeGreaterThanOrEqual(15)
  expect(primary.height).toBeGreaterThanOrEqual(40)
  await expect(context.locator('[data-section-id] h3')).toBeInViewport()
  await page.screenshot({ path: resolve('..', '.ci/browser/clarity-context.png'), animations: 'disabled' })
  const pin = page.getByRole('button', { name: '固定提问目标', exact: true })
  await pin.click()
  await expect(pin).toHaveAttribute('aria-pressed', 'true')
  await pin.click()
  await expect(pin).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.reading-target summary')).toContainText('一次下单要改两张表')
  await expect(page.locator('[data-material-toggle]')).not.toContainText('有新来源')
  await expect(page.getByRole('button', { name: '有新的回答来源，点击查看', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '隐藏材料区域', exact: true }).click()
  await expect(page.locator('[data-material-toggle]')).toContainText('有新来源')
  await page.locator('[data-material-toggle]').click()
  for (const width of [900, 1024, 1280, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await expect(full).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await full.click()
  await expect(page.locator('.learning-article')).toBeVisible()
})
